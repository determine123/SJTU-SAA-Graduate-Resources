"""Order-4 B-spline learning example (Python 3).
Run: python cad_bspline.py
Dependencies: numpy, matplotlib. Outputs: two PNG figures and curve_samples.csv.
The numerical knot vector below is an explicit clamped-uniform choice.
"""
from pathlib import Path
import numpy as np
import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt

POINTS = np.array([(0, 0), (20, 10), (40, 15), (60, 5),
                   (60, -20), (40, -30), (20, -30)], dtype=float)
KNOTS = np.array([0, 0, 0, 0, 1, 2, 3, 4, 4, 4, 4], dtype=float)
DEGREE = 3  # Order = DEGREE + 1 = 4.

def basis(u, knots=KNOTS, degree=DEGREE):
    """All basis values via Cox-de Boor; repeated-knot terms equal zero."""
    count = len(knots) - degree - 1
    if not knots[degree] <= u <= knots[count]:
        raise ValueError('Parameter outside the active knot interval.')
    if u == knots[count]:  # Closed right endpoint for this clamped vector.
        values = np.zeros(count)
        values[-1] = 1.0
        return values
    values = ((knots[:-1] <= u) & (u < knots[1:])).astype(float)
    for d in range(1, degree + 1):
        updated = np.zeros(len(knots) - d - 1)
        for i in range(len(updated)):
            left = knots[i + d] - knots[i]
            right = knots[i + d + 1] - knots[i + 1]
            if left > 0:
                updated[i] += (u - knots[i]) / left * values[i]
            if right > 0:
                updated[i] += (knots[i + d + 1] - u) / right * values[i + 1]
        values = updated
    return values

def main():
    output = Path(__file__).resolve().parent
    u = np.linspace(0, 4, 801)
    weights = np.array([basis(t) for t in u])
    curve = weights @ POINTS
    assert np.isfinite(curve).all()
    assert np.min(weights) >= -1e-12
    assert np.max(np.abs(weights.sum(axis=1) - 1)) < 1e-12
    assert np.allclose(curve[[0, -1]], POINTS[[0, -1]])
    np.savetxt(output / 'curve_samples.csv', np.column_stack((u, curve)),
               delimiter=',', header='u,x,y', comments='', fmt='%.12g')
    plt.rcParams.update({'font.family': 'DejaVu Serif', 'font.size': 10})
    fig, ax = plt.subplots(figsize=(6.8, 3.0))
    for i in range(7):
        ax.plot(u, weights[:, i], label=f'N{i},4')
    ax.set(xlabel='Parameter u (dimensionless)', ylabel='Basis value (dimensionless)',
           title='Seven order-4 B-spline basis functions', xlim=(0, 4))
    ax.legend(ncol=4, fontsize=8); ax.grid(alpha=.2)
    fig.tight_layout(); fig.savefig(output / 'bspline_basis.png', dpi=250)
    plt.close(fig)
    fig, ax = plt.subplots(figsize=(6.8, 4.0))
    ax.plot(*POINTS.T, 'o--', color='0.55', label='Control polygon')
    ax.plot(*curve.T, color='#173f68', linewidth=2, label='Cubic B-spline')
    for i, point in enumerate(POINTS):
        ax.annotate(f'P{i}', point, xytext=(5, 6), textcoords='offset points')
    ax.set(xlabel='x (coordinate units)', ylabel='y (coordinate units)',
           title='Order-4 B-spline generated by the seven example control points')
    ax.set_aspect('equal', adjustable='box'); ax.legend(fontsize=8)
    ax.grid(alpha=.2); fig.tight_layout()
    fig.savefig(output / 'bspline_curve.png', dpi=250); plt.close(fig)
    print('PASS: nonnegative basis, partition of unity, finite values and endpoints.')

if __name__ == '__main__':
    main()
